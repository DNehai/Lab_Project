attempts = 0    #Счётчик попыток
cons_num = 56   #Число, которое нужно угадать
print("Угадай число")   #Вывод названия игры
while True:     #Основной цикл while
    command = int(input('''1.Guess
2.Hint
3.New
4.Exit
Выберете номер команды: '''))       #Вывод меню выбора команд
    if command == 1:                            #Команда guess
        guess = int(input("Введите число: "))
        if guess == cons_num:                   #Проверка угадал ли пользователь число
            attempts += 1                       #Повышение счётчика попыток
            print(f'''Вы угадали число! Победа!
Количество попыток: {attempts}''')              #Вывод текста и кол-ва попыток в случае победа
            if input("Хотите продолжить?[1 - да|0 - нет]: ") == '1':    #Проверка хочет ли пользователь играть дальше
                print("Загадываем новое число...")
            else:
                break
        else:
            attempts += 1                       #Повышение счётчика попыток
            if guess < cons_num:                #Проверка больше или меньше число загаданного числа и вывод соответсвующего текста
                print("Вы назвали число меньшее загаданного. Попробуйте ещё раз.")
            else:
                print("Вы назвали число большее загаданного. Попробуйте ещё раз.")

    elif command == 2:                            #Комманда hint
        if cons_num%2==0:                       #Проверка чётности и вывод соответствующей подсказки
            print("Число чётное.")
        else:
            print("Число нечётное.")
    elif command == 3:                            #Команда new
        print("Загадываем новое число...")
        attempts = 0                            #Обнуление счётчика
    elif command == 4:                            #Команда exit
        print("Завершаем игру...")
        break                                   #Завершение цикла